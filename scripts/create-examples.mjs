await mkdir('docs/examples', { recursive: true });
const manifest = existsSync('docs/examples/manifest.json')
  ? JSON.parse(await readFile('docs/examples/manifest.json', 'utf8'))
  : [];
for (const [id, component, title, description, imports, body] of examples) {
  // 已维护的示例由其源码负责，重跑种子脚本不覆盖后续修正或删除新增示例。
  if (manifest.some((item) => item.id === id)) continue;
  const source = `import { useRef, useState } from 'react';\nimport { ${imports} } from 'element-react';\nimport type { ChoiceValue, InputHandle } from 'element-react';\n\n/** ${description} */\nexport default function Example() {\n  ${body}\n}\n`;
  // 每个示例只保留实际使用的Hooks及类型，使类型/规范检查覆盖真实示例。
  const cleaned = source
    .replace(
      "import { useRef, useState } from 'react';\n",
      body.includes('useRef') || body.includes('useState')
        ? `import { ${[body.includes('useRef') && 'useRef', body.includes('useState') && 'useState'].filter(Boolean).join(', ')} } from 'react';\n`
        : '',
    )
    .replace(
      "import type { ChoiceValue, InputHandle } from 'element-react';\n",
      body.includes('ChoiceValue') || body.includes('InputHandle')
        ? `import type { ${[body.includes('ChoiceValue') && 'ChoiceValue', body.includes('InputHandle') && 'InputHandle'].filter(Boolean).join(', ')} } from 'element-react';\n`
        : '',
    );
  await writeFile(`docs/examples/${id}.tsx`, cleaned);
  manifest.push({ id, component, title, description, source: `docs/examples/${id}.tsx` });
}
await writeFile('docs/examples/manifest.json', JSON.stringify(manifest, null, 2) + '\n');
console.log(`已生成 ${manifest.length} 个可运行React示例。`);
